    def test_hostile_11_biscuit_custody_no_leak(self, _client: TestClient, _fixtures: dict) -> None:
        """Test M: Mount response must not contain biscuit_token."""
        # Register package first so mount succeeds
        from cappo_backend.capability_mount.models import CapabilityPackage
        pkg = CapabilityPackage(
            id="sandbox-file-append@v1",
            family="sandbox",
            title="Sandbox File Append",
            purpose="Append content to a sandboxed file for testing",
            reads=["fs.read"], writes=["fs.write"], blocked=[], outputs=["fs.result"],
            policy_defaults={"mode": "draft_only"}, external_send_actions=[], suppression_required_actions=[]
        )
        _client.app.state.mount_registry.register_package(pkg)
        
        r = _client.post(
            "/v1/capability/mounts",
            json={
                "package_ref": "sandbox-file-append@v1",
                "execution_scope": {"workspace": "test-workspace", "project": "test-project"},
                "ttl_seconds": 10,
            },
        )
        assert r.status_code == 200, f"Mount returned {r.status_code}: {r.text[:200]}"
        assert "biscuit_token" not in r.text, (
            f"CUSTODY LEAK: biscuit_token present in serialized mount response. Body: {r.text[:400]}"
        )
        body = r.json()
        _record(
            "HOSTILE-11",
            "Test M: Mount Response Excludes Raw Biscuit Token",
            200,
            r.status_code,
            {"biscuit_token_absent": True, "decision": body.get("decision")},
        )

    def test_seal_evidence(self, _client: TestClient, _fixtures: dict) -> None:
        """Seal all evidence collected during this battery run to the evidence file."""
        EVIDENCE_DIR.mkdir(parents=True, exist_ok=True)
        passed = sum(1 for r in _evidence if r["passed"])
        total = len(_evidence)
        evidence = {
            "audit_title": "Veklom CAPPO Hostile Request Battery — Canonical Proof",
            "test_environment": "TestClient + SQLite battery.db (auth_enabled=False)",
            "authority_boundary": (
                "All Biscuit tokens read from hostile_fixtures.json. "
                "No mint_biscuit_capability called in client code anywhere."
            ),
            "run_timestamp": datetime.now(timezone.utc).isoformat(),
            "total_tests": total,
            "passed_tests": passed,
            "all_tests_passed": passed == total,
            "raw_responses": _evidence,
        }
        EVIDENCE_FILE.write_text(json.dumps(evidence, indent=2), encoding="utf-8")
        assert passed == total, (
            f"Battery not clean: {passed}/{total} passed. Evidence: {EVIDENCE_FILE}"
        )
