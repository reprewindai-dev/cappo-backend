# ── Module-level evidence accumulator ────────────────────────────────────────
_evidence: list[dict[str, Any]] = []

def _record(tc_id: str, name: str, expected: int, actual: int, body: Any) -> bool:
    passed = actual == expected
    _evidence.append({
        "test_id": tc_id,
        "test_name": name,
        "timestamp_iso8601": datetime.now(timezone.utc).isoformat(),
        "passed": passed,
        "expected_status": expected,
        "actual_status": actual,
        "response_body": body if isinstance(body, dict) else str(body)[:300],
    })
    return passed


