"""CAPPO runtime FastAPI application.

Middleware stack order, outermost → innermost:
    1. RequestLogging
    2. CORS
    3. Amphoteric sensing
    4. Auth
    5. Ollama lifecycle policy signal

Budget / kill-switch and EI / LAW 0 remain enforced inside the governed
execution pipeline. There is no public bypass for ``/v1/exec``.

Synthetic/random VNP measurements are deliberately absent. VNP trust/evidence
must be derived from attributable external probe telemetry, never generated by
this application process.
"""

